import { ref } from 'vue'
import type { DiagnosisResult } from './api'

export type Lang = 'zh' | 'en'

function detectInitialLang(): Lang {
  try {
    const saved = localStorage.getItem('ipsecvpn_lang')
    if (saved === 'en' || saved === 'zh') return saved
  } catch {
    // ignore storage errors
  }
  return 'zh'
}

export const lang = ref<Lang>(detectInitialLang())

function syncDocumentTitle(l: Lang) {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = l === 'en' ? 'en' : 'zh-CN'
    document.title = l === 'en' ? 'VPN Gateway Console · event-ipsec-hub' : 'VPN 网关控制台 · event-ipsec-hub'
  }
}
syncDocumentTitle(lang.value)

export function setLang(next: Lang) {
  lang.value = next
  try {
    localStorage.setItem('ipsecvpn_lang', next)
  } catch {
    // ignore
  }
  syncDocumentTitle(next)
}

export function toggleLang() {
  setLang(lang.value === 'zh' ? 'en' : 'zh')
}

